#!/usr/bin/env python3
"""The RichTextFix plugin's style list, for the no-highlight check.

Reads `ArknightsLocalization.RichTextFix.dll` (the file only, never loaded),
finds its gzip-compressed `CnRichStyles` resource (a JSON object with
`styles`: `name -> <color=#…>{0}</color>`) and writes the names into
`frontend/src/components/translators/pluginStyles.ts` and
`backend/src/translators/texts/plugin_styles.rs`. Run after the pack updates
the plugin:

    python3 translators/tools/plugin_styles.py /path/to/ArknightsLocalization.RichTextFix.dll
"""

import json
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TS = ROOT / "frontend/src/components/translators/pluginStyles.ts"
RS = ROOT / "backend/src/translators/texts/plugin_styles.rs"


def styles_of(dll: bytes) -> dict[str, str]:
    """The `styles` object of the first gzip stream in the DLL that holds one."""
    at = 0
    while True:
        at = dll.find(b"\x1f\x8b\x08", at)
        if at < 0:
            raise SystemExit("no CnRichStyles resource found in the DLL")
        try:
            out = zlib.decompressobj(16 + zlib.MAX_WBITS).decompress(dll[at:])
            data = json.loads(out)
            if isinstance(data, dict) and "styles" in data:
                return data["styles"]
        except (zlib.error, ValueError, UnicodeDecodeError):
            pass
        at += 3


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    names = sorted(styles_of(Path(sys.argv[1]).read_bytes()))
    note = (
        "The game styles the RichTextFix plugin knows (its `CnRichStyles` resource):\n"
        " * a `<@name>…</>` of the original becomes a colour (or italics) the plugin\n"
        " * can put back into a plain translation; a name not here is dropped, so its\n"
        " * highlight is lost for good. Matched exactly (the plugin compares\n"
        " * case-sensitively): the game's `@act.timeLimit` is not its `act.timelimit`.\n"
        " * Every `<$…>` term is the `ba.kw` colour. Generated by\n"
        " * translators/tools/plugin_styles.py from the plugin DLL; the same list stands in"
    )
    TS.write_text(
        "/**\n * " + note + "\n * `backend/src/translators/texts/plugin_styles.rs`.\n */\n"
        "export const PLUGIN_STYLES: ReadonlySet<string> = new Set([\n"
        + "".join(f'    "{n}",\n' for n in names)
        + "]);\n"
    )
    rs_note = "\n".join("//!" + line[2:] if line.startswith(" *") else "//! " + line for line in note.split("\n"))
    RS.write_text(
        rs_note + "\n//! `frontend/src/components/translators/pluginStyles.ts`.\n\n"
        "pub const PLUGIN_STYLES: &[&str] = &[\n"
        + "".join(f'    "{n}",\n' for n in names)
        + "];\n\n/// Whether the plugin knows a style (the name after `@`).\n"
        "pub fn known(name: &str) -> bool {\n    PLUGIN_STYLES.binary_search(&name).is_ok()\n}\n"
    )
    print(f"{len(names)} styles written to {TS.relative_to(ROOT)} and {RS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
